export function getSefazUrl(uf, ambiente, servico) {
  const isHomologacao = Number(ambiente) === 2;
  const mapa = isHomologacao ? URLS_HOMOLOGACAO : URLS_PRODUCAO;
  const estado = String(uf || 'AM').toUpperCase();

  if (mapa[estado] && mapa[estado][servico]) {
    return mapa[estado][servico];
  }
  if (mapa.SVRS && mapa.SVRS[servico]) {
    return mapa.SVRS[servico];
  }
  if (URLS_HOMOLOGACAO.AM && URLS_HOMOLOGACAO.AM[servico]) {
    return URLS_HOMOLOGACAO.AM[servico];
  }

  throw new Error(`URL da SEFAZ não configurada para UF: ${estado}, ambiente: ${ambiente}, servico: ${servico}`);
}
